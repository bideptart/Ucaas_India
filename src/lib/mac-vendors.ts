/* One lookup table, built once. */
const TABLE = new Map<string, MacVendor>();
for (const [vendor, name, run] of SUPPORTED) {
  for (let i = 0; i < run.length; i += 6) TABLE.set(run.slice(i, i + 6), { kind: 'supported', vendor, name });
}
for (const [name, run] of OTHERS) {
  for (let i = 0; i < run.length; i += 6) TABLE.set(run.slice(i, i + 6), { kind: 'other', name });
}

/** The maker of the phone this MAC belongs to, or null when the prefix is not
 *  one we hold - which includes every made-up or locally administered address.
 *  Anything that is not a hex digit is ignored, so a MAC may be typed with
 *  colons, dashes, spaces or none of them. */
export function vendorFromMac(mac: unknown): MacVendor | null {
  const hex = String(mac ?? '').toUpperCase().replace(/[^0-9A-F]/g, '');
  if (hex.length < 6) return null;
  return TABLE.get(hex.slice(0, 6)) ?? null;
}
